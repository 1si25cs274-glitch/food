@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun OnboardingScreen(
    uid: String,
    email: String,
    initialDisplayName: String,
    selectedLanguage: AppLanguage,
    isBusy: Boolean,
    onSaveProfile: (UserProfile) -> Unit
) {
    var displayName by remember { mutableStateOf(initialDisplayName.ifBlank { "FoodBridge Member" }) }
    var accountType by remember { mutableStateOf("donor") }
    var orgName by remember { mutableStateOf("") }
    var phoneDigits by remember { mutableStateOf("") }
    var otpGenerated by remember { mutableStateOf<String?>(null) }
    var otpInput by remember { mutableStateOf("") }
    var phoneVerified by remember { mutableStateOf(false) }

    val states = IndiaData.statesToDistricts.keys.toList()
    var selectedState by remember { mutableStateOf("Karnataka") }
    var stateExpanded by remember { mutableStateOf(false) }
    val districts = IndiaData.statesToDistricts[selectedState] ?: listOf("Bengaluru Urban")
    var selectedDistrict by remember { mutableStateOf(districts.first()) }
    var districtExpanded by remember { mutableStateOf(false) }

    var address by remember { mutableStateOf("") }
    var pinCode by remember { mutableStateOf("560038") }
    var fssaiOrNgoId by remember { mutableStateOf("") }
    var sharePhoneConsent by remember { mutableStateOf(true) }
    var shareLocationConsent by remember { mutableStateOf(true) }
    var whatsappAlerts by remember { mutableStateOf(true) }
    var validationError by remember { mutableStateOf<String?>(null) }

    Scaffold(
        topBar = {
            TopAppBar(
                title = { Text("Complete Registration", fontWeight = FontWeight.Bold) }
            )
        }
    ) { innerPadding ->
        Box(
            modifier = Modifier
                .fillMaxSize()
                .padding(innerPadding),
            contentAlignment = Alignment.TopCenter
        ) {
            Column(
                modifier = Modifier
                    .widthIn(max = 600.dp)
                    .fillMaxSize()
                    .verticalScroll(rememberScrollState())
                    .padding(16.dp),
                verticalArrangement = Arrangement.spacedBy(14.dp)
            ) {
                Text(
                    text = "Select Your FoodBridge India Role",
                    style = MaterialTheme.typography.titleMedium,
                    fontWeight = FontWeight.Bold
                )
                Row(
                    modifier = Modifier.fillMaxWidth(),
                    horizontalArrangement = Arrangement.spacedBy(8.dp)
                ) {
                    listOf(
                        Triple("donor", "Donor", Icons.Default.Restaurant),
                        Triple("receiver", "NGO / Receiver", Icons.Default.VolunteerActivism),
                        Triple("volunteer", "Volunteer", Icons.Default.LocalShipping)
                    ).forEach { (roleKey, label, icon) ->
                        FilterChip(
                            selected = accountType == roleKey,
                            onClick = { accountType = roleKey },
                            label = { Text(label) },
                            leadingIcon = { Icon(icon, contentDescription = null) },
                            modifier = Modifier
                                .weight(1f)
                                .testTag("role_chip_$roleKey")
                        )
                    }
                }

                OutlinedTextField(
                    value = displayName,
                    onValueChange = { displayName = it },
                    label = { Text("Full Name *") },
                    modifier = Modifier.fillMaxWidth(),
                    singleLine = true
                )

                OutlinedTextField(
                    value = orgName,
                    onValueChange = { orgName = it },
                    label = {
                        Text(
                            when (accountType) {
                                "donor" -> "Restaurant / Hotel / Event / Kitchen Name"
                                "receiver" -> "NGO / Shelter / Orphanage Name"
                                else -> "Volunteer Group / College (Optional)"
                            }
                        )
                    },
                    modifier = Modifier.fillMaxWidth(),
                    singleLine = true
                )

                ElevatedCard(
                    modifier = Modifier.fillMaxWidth(),
                    shape = RoundedCornerShape(18.dp)
                ) {
                    Column(
                        modifier = Modifier.padding(14.dp),
                        verticalArrangement = Arrangement.spacedBy(10.dp)
                    ) {
                        Text(
                            text = "Indian Mobile (+91) & OTP Verification",
                            style = MaterialTheme.typography.titleSmall,
                            fontWeight = FontWeight.Bold
                        )
                        Row(
                            modifier = Modifier.fillMaxWidth(),
                            horizontalArrangement = Arrangement.spacedBy(8.dp),
                            verticalAlignment = Alignment.CenterVertically
                        ) {
                            OutlinedTextField(
                                value = phoneDigits,
                                onValueChange = {
                                    phoneDigits = it.filter { c -> c.isDigit() }.take(10)
                                    phoneVerified = false
                                },
                                prefix = { Text("+91 ") },
                                label = { Text("10-digit Mobile *") },
                                keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Phone),
                                modifier = Modifier
                                    .weight(1f)
                                    .testTag("onboarding_phone_input"),
                                singleLine = true
                            )
                            OutlinedButton(
                                onClick = {
                                    if (!IndiaData.isValidIndianMobile(phoneDigits)) {
                                        validationError = "Enter a valid 10-digit Indian mobile number starting with 6–9."
                                    } else {
                                        validationError = null
                                        otpGenerated = Random.nextInt(1000, 9999).toString()
                                    }
                                }
                            ) {
                                Text(if (otpGenerated == null) "Send OTP" else "Resend")
                            }
                        }

                        if (otpGenerated != null && !phoneVerified) {
                            Surface(
                                color = MaterialTheme.colorScheme.primaryContainer,
                                shape = RoundedCornerShape(10.dp),
                                modifier = Modifier.fillMaxWidth()
                            ) {
                                Text(
                                    text = "Verification OTP sent to +91 $phoneDigits (Demo code: $otpGenerated)",
                                    style = MaterialTheme.typography.bodySmall,
                                    modifier = Modifier.padding(10.dp)
                                )
                            }
                            Row(
                                modifier = Modifier.fillMaxWidth(),
                                horizontalArrangement = Arrangement.spacedBy(8.dp),
                                verticalAlignment = Alignment.CenterVertically
                            ) {
                                OutlinedTextField(
                                    value = otpInput,
                                    onValueChange = { otpInput = it.filter { c -> c.isDigit() }.take(4) },
                                    label = { Text("Enter 4-digit OTP") },
                                    keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Number),
                                    modifier = Modifier.weight(1f),
                                    singleLine = true
                                )
                                Button(
                                    onClick = {
                                        if (otpInput == otpGenerated) {
                                            phoneVerified = true
                                            validationError = null
                                        } else {
                                            validationError = "Incorrect OTP code. Please check $otpGenerated."
                                        }
                                    }
                                ) {
                                    Text("Verify")
                                }
                            }
                        }

                        if (phoneVerified) {
                            Row(verticalAlignment = Alignment.CenterVertically) {
                                Icon(Icons.Default.CheckCircle, contentDescription = null, tint = EmeraldPrimary)
                                Text(
                                    text = " +91 $phoneDigits verified",
                                    color = EmeraldPrimary,
                                    fontWeight = FontWeight.SemiBold
                                )
                            }
                        }
                    }
                }

                // State & District Cascade
                Row(
                    modifier = Modifier.fillMaxWidth(),
                    horizontalArrangement = Arrangement.spacedBy(10.dp)
                ) {
                    ExposedDropdownMenuBox(
                        expanded = stateExpanded,
                        onExpandedChange = { stateExpanded = !stateExpanded },
                        modifier = Modifier.weight(1f)
                    ) {
                        OutlinedTextField(
                            value = selectedState,
                            onValueChange = {},
                            readOnly = true,
                            label = { Text("State") },
                            trailingIcon = { ExposedDropdownMenuDefaults.TrailingIcon(expanded = stateExpanded) },
                            modifier = Modifier.menuAnchor(MenuAnchorType.PrimaryNotEditable)
                        )
                        ExposedDropdownMenu(
                            expanded = stateExpanded,
                            onDismissRequest = { stateExpanded = false }
                        ) {
                            states.forEach { stateName ->
                                DropdownMenuItem(
                                    text = { Text(stateName) },
                                    onClick = {
                                        selectedState = stateName
                                        selectedDistrict = IndiaData.statesToDistricts[stateName]?.firstOrNull() ?: ""
                                        stateExpanded = false
                                    }
                                )
                            }
                        }
                    }

                    ExposedDropdownMenuBox(
                        expanded = districtExpanded,
                        onExpandedChange = { districtExpanded = !districtExpanded },
                        modifier = Modifier.weight(1f)
                    ) {
                        OutlinedTextField(
                            value = selectedDistrict,
                            onValueChange = {},
                            readOnly = true,
                            label = { Text("District") },
                            trailingIcon = { ExposedDropdownMenuDefaults.TrailingIcon(expanded = districtExpanded) },
                            modifier = Modifier.menuAnchor(MenuAnchorType.PrimaryNotEditable)
                        )
                        ExposedDropdownMenu(
                            expanded = districtExpanded,
                            onDismissRequest = { districtExpanded = false }
                        ) {
                            districts.forEach { distName ->
                                DropdownMenuItem(
                                    text = { Text(distName) },
                                    onClick = {
                                        selectedDistrict = distName
                                        districtExpanded = false
                                    }
                                )
                            }
                        }
                    }
                }

                Row(
                    modifier = Modifier.fillMaxWidth(),
                    horizontalArrangement = Arrangement.spacedBy(10.dp)
                ) {
                    OutlinedTextField(
                        value = pinCode,
                        onValueChange = { pinCode = it.filter { c -> c.isDigit() }.take(6) },
                        label = { Text("PIN Code *") },
                        keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Number),
                        modifier = Modifier.weight(1f),
                        singleLine = true
                    )
                    OutlinedTextField(
                        value = fssaiOrNgoId,
                        onValueChange = { fssaiOrNgoId = it },
                        label = { Text("FSSAI / NGO Darpan ID") },
                        modifier = Modifier.weight(1.4f),
                        singleLine = true
                    )
                }

                OutlinedTextField(
                    value = address,
                    onValueChange = { address = it },
                    label = { Text("Street Address / Landmark") },
                    modifier = Modifier.fillMaxWidth(),
                    maxLines = 2
                )

                // DPDP Privacy Consents
                Column(verticalArrangement = Arrangement.spacedBy(4.dp)) {
                    Row(verticalAlignment = Alignment.CenterVertically) {
                        Checkbox(checked = sharePhoneConsent, onCheckedChange = { sharePhoneConsent = it })
                        Text(
                            "Allow Call/WhatsApp contact only with matched pickup parties",
                            style = MaterialTheme.typography.bodySmall
                        )
                    }
                    Row(verticalAlignment = Alignment.CenterVertically) {
                        Checkbox(checked = shareLocationConsent, onCheckedChange = { shareLocationConsent = it })
                        Text(
                            "Keep exact GPS private until food request is accepted",
                            style = MaterialTheme.typography.bodySmall
                        )
                    }
                    Row(verticalAlignment = Alignment.CenterVertically) {
                        Checkbox(checked = whatsappAlerts, onCheckedChange = { whatsappAlerts = it })
                        Text(
                            "Enable WhatsApp & push alerts for nearby donations",
                            style = MaterialTheme.typography.bodySmall
                        )
                    }
                }

                if (validationError != null) {
                    Surface(
                        color = MaterialTheme.colorScheme.errorContainer,
                        shape = RoundedCornerShape(12.dp),
                        modifier = Modifier.fillMaxWidth()
                    ) {
                        Text(
                            text = validationError.orEmpty(),
                            color = MaterialTheme.colorScheme.onErrorContainer,
                            style = MaterialTheme.typography.bodySmall,
                            modifier = Modifier.padding(12.dp)
                        )
                    }
                }

                Button(
                    onClick = {
                        when {
                            displayName.trim().length < 2 ->
                                validationError = "Please enter your full name."
                            !IndiaData.isValidIndianMobile(phoneDigits) ->
                                validationError = "Please enter a valid 10-digit +91 mobile number."
                            !IndiaData.isValidPinCode(pinCode) ->
                                validationError = "Please enter a valid 6-digit Indian PIN code."
                            else -> {
                                validationError = null
                                onSaveProfile(
                                    UserProfile(
                                        userId = uid,
                                        displayName = displayName.trim(),
                                        email = email,
                                        phone = IndiaData.normalizeIndianPhone(phoneDigits),
                                        accountType = accountType,
                                        organizationName = orgName.trim().ifBlank { displayName.trim() },
                                        address = address.trim().ifBlank { "$selectedDistrict, $selectedState" },
                                        district = selectedDistrict,
                                        state = selectedState,
                                        pinCode = pinCode,
                                        fssaiOrNgoId = fssaiOrNgoId.trim(),
                                        preferredLanguage = selectedLanguage.code,
                                        sharePhoneWithMatchedParties = sharePhoneConsent,
                                        shareExactLocationOnAccept = shareLocationConsent,
                                        whatsappAlertsEnabled = whatsappAlerts
                                    )
                                )
                            }
                        }
                    },
                    enabled = !isBusy,
                    modifier = Modifier
                        .fillMaxWidth()
                        .height(54.dp)
                        .testTag("complete_registration_button"),
                    shape = RoundedCornerShape(16.dp)
                ) {
                    Text(if (isBusy) "Saving Profile..." else "Save & Enter FoodBridge India")
                }

                Spacer(modifier = Modifier.height(16.dp))
            }
        }
    }
}
